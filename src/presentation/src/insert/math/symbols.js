const table = (map, cls) =>
  Object.fromEntries(
    Object.entries(map).map(([name, glyph]) => [name, { glyph, cls }]),
  );

/** Every single-character command: name → { glyph, cls }. */
export const SYMBOLS = {
  ...table(GREEK, "ord"),
  ...table(ORD, "ord"),
  ...table(BIN, "bin"),
  ...table(REL, "rel"),
};

/** Class of a plain character typed directly. */
export function charClass(ch) {
  if ("+-−±×÷⋅∗".includes(ch)) return "bin";
  if ("=<>≤≥≠≈≡∼→←⇒⇔∈∉⊂⊃⊆⊇:".includes(ch)) return "rel";
  if ("([{⟨".includes(ch)) return "open";
  if (")]}⟩".includes(ch)) return "close";
  if (",;".includes(ch)) return "punct";
  return "ord";
}

