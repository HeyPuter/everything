"""Build src/vendor/words-en.js, the spelling checker's English word lists, from the SCOWL-derived
Hunspell dictionaries (MIT AND BSD licensed; see src/vendor/SCOWL-LICENSE.txt).

  npm pack dictionary-en@4.0.0 dictionary-en-gb@3.0.0   (in an empty folder; unpack each .tgz)
  python3 dev/generate-word-lists.py <dictionary-en/package> <dictionary-en-gb/package>

Every word form the affix rules allow is listed (words with digits left out), the possessives ("'s")
dropped because the checker accepts them by rule, and each list sorted and front-coded."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent

def expand(folder):
    folder = pathlib.Path(folder)
    lines = (folder / 'index.aff').read_text(encoding='utf-8').split('\n')
    pfx, sfx, i = {}, {}, 0
    while i < len(lines):
        parts = lines[i].split()
        if parts and parts[0] in ('PFX', 'SFX') and len(parts) == 4:
            kind, flag, cross, n = parts
            rules = []
            for j in range(int(n)):
                p = lines[i + 1 + j].split()
                strip = '' if p[2] == '0' else p[2]
                add = '' if p[3] == '0' else p[3].split('/')[0]
                cond = p[4] if len(p) > 4 else '.'
                rules.append((strip, add, re.compile(('^' + cond) if kind == 'PFX' else (cond + '$'))))
            (pfx if kind == 'PFX' else sfx)[flag] = (cross == 'Y', rules)
            i += 1 + int(n)
            continue
        i += 1

    def suffixed(stem, flags):
        out = []
        for fl in flags:
            for strip, add, rx in sfx.get(fl, (False, []))[1]:
                if rx.search(stem) and stem.endswith(strip):
                    out.append(((stem[:len(stem) - len(strip)] if strip else stem) + add, sfx[fl][0]))
        return out

    def prefixed(word, flags):
        out = []
        for fl in flags:
            for strip, add, rx in pfx.get(fl, (False, []))[1]:
                if rx.search(word) and word.startswith(strip):
                    out.append((add + word[len(strip):], pfx[fl][0]))
        return out

    words, nosuggest = set(), set()
    for line in (folder / 'index.dic').read_text(encoding='utf-8').split('\n')[1:]:
        entry = line.strip().split('\t')[0].split(' ')[0]
        if not entry:
            continue
        stem, _, flags = entry.partition('/')
        if any(ch.isdigit() for ch in stem):
            continue
        forms = {stem}
        sx = suffixed(stem, flags)
        forms.update(w for w, _ in sx)
        for w, cross in prefixed(stem, flags):
            forms.add(w)
            if cross:
                for sw, scross in sx:
                    if scross:
                        forms.update(pw for pw, _ in prefixed(sw, flags))
        (nosuggest if '!' in flags else words).update(forms)
    return words, nosuggest

def front(words):
    out, prev = [], ''
    for w in sorted(words):
        n = 0
        while n < min(len(prev), len(w), 60) and prev[n] == w[n]:
            n += 1
        out.append(chr(48 + n) + w[n:])
        prev = w
    text = '\n'.join(out)
    assert '`' not in text and '\\' not in text and '${' not in text
    return '`' + text + '`'

us, nosuggest = expand(sys.argv[1])
gb, _ = expand(sys.argv[2])
plain = lambda s: {w for w in s if not (w.endswith("'s") and w[:-2] in s)}
us, gb = plain(us), plain(gb)
(root / 'src/vendor/words-en.js').write_text(
    '/* English word lists derived from SCOWL / the en_US and en_GB Hunspell dictionaries\n'
    ' * (see SCOWL-LICENSE.txt beside this file). Generated by dev/generate-word-lists.py; each list is\n'
    ' * sorted and front-coded: one word per line, its first character the count of leading characters\n'
    ' * shared with the word before (as the character code minus 48), then the rest of the word.\n'
    ' * Possessives ("\'s") are left out and accepted by rule. Do not edit by hand. */\n'
    f'export const EN_US = {front(us)};\n'
    f'export const EN_GB_ADD = {front(gb - us)};\n'
    f'export const EN_GB_DROP = {front(us - gb)};\n'
    f'export const NO_SUGGEST = {front(nosuggest)};\n', encoding='utf-8')
print(len(us), 'American words;', len(gb - us), 'British only;', len(us - gb), 'American only')
