const rules = {};
// The translated message for a count, with {count} still to fill in.
export function counted(text, count) {
  const locale = language === "fr" ? "fr-CA" : "en-CA";
  rules[locale] ??= new Intl.PluralRules(locale);
  return t(
    SINGULAR[text] && rules[locale].select(count) === "one"
      ? SINGULAR[text][0]
      : text,
  );
}
