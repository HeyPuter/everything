const SVG_NS = 'http://www.w3.org/2000/svg';

function build(nodes, size) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', size >= 28 ? '1.35' : size <= 16 ? '1.75' : '1.6');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.classList.add('icon');
  for (const [tag, attrs] of nodes) {
    const el = document.createElementNS(SVG_NS, tag);
    for (const [k, v] of Object.entries(attrs)) if (v !== '') el.setAttribute(k, String(v));
    svg.appendChild(el);
  }
  return svg;
}

export function icon(name, size = 18) {
  const nodes = BIM[name] ?? LUCIDE[name];
  return build(nodes || [], size);
}

export function hasIcon(name) {
  return name in BIM || name in LUCIDE;
}

