// renders

interface RenderDuplis {
  meshes: Mesh[];
  key: string;
}
const renderState = new WeakMap<object, RenderDuplis>();

renderSceneHooks.push((rs, a, o) => {
  const doc = a.doc;
  const graph = a.graph;
  const keys: string[] = [];
  const instancers: EvalObject[] = [];
  for (const ev of graph.objects.values()) {
    if (!ev.ob.instance_type || ev.ob.instance_type === 'NONE') continue;
    if (o.final ? ev.ob.hide_render : !ev.visible || (o.localView && !o.localView.has(ev.id))) continue;
    const k = dupliKey(doc, graph, ev);
    if (!k) continue;
    keys.push(k);
    instancers.push(ev);
  }
  const key = `${rs.mode}#${keys.join('#')}`;
  const st = renderState.get(rs) ?? { meshes: [], key: '' };
  renderState.set(rs, st);
  if (st.key === key) return;
  st.key = key;
  for (const m of st.meshes) rs.scene.remove(m);
  st.meshes = [];
  for (const ev of instancers) {
    for (const [src, mats] of groupDuplis(objectDuplis(doc, graph, ev.ob))) {
      const sev = graph.get(src);
      if (!sev?.mesh) continue;
      const geo = meshGeometry(sev.mesh).geometry;
      const slots = materialSlots(doc, sev.ob);
      const n = Math.max(1, ...geo.groups.map((gr) => (gr.materialIndex ?? 0) + 1));
      const materials: Material[] = [];
      for (let i = 0; i < n; i++) {
        const vm = viewportMaterial(doc, slots[i] ?? null);
        materials.push(rs.mode === 'pathtrace' ? pathTracerMaterial(vm) : vm);
      }
      const material = materials.length === 1 ? materials[0] : materials;
      if (rs.mode === 'raster') {
        const im = new InstancedMesh(geo, material, mats.length);
        mats.forEach((m, i) => im.setMatrixAt(i, m));
        im.instanceMatrix.needsUpdate = true;
        im.computeBoundingSphere();
        im.matrixAutoUpdate = false;
        im.castShadow = im.receiveShadow = true;
        im.userData.id = ev.id;
        st.meshes.push(im);
      } else
        for (const m of mats) {
          const mesh = new Mesh(geo, material);
          mesh.matrixAutoUpdate = false;
          mesh.matrix.copy(m);
          mesh.castShadow = mesh.receiveShadow = true;
          mesh.userData.id = ev.id;
          st.meshes.push(mesh);
        }
    }
  }
  for (const m of st.meshes) rs.scene.add(m);
  rs.structureVersion++;
});

