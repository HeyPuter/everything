export interface Dupli {
  /** object being repeated */
  source: string;
  /** world matrix of this instance */
  matrix: Matrix4;
}

const MAX_DEPTH = 8;
/** edge length of the quads written by Make Instance Face (scaled back up by the instancer) */
const FACE_SIZE = 0.01;

/** Objects of a collection and its child collections. */
export function collectionObjectIds(doc: DocumentData, cid: string, out = new Set<string>(), seen = new Set<string>()): Set<string> {
  if (seen.has(cid)) return out;
  seen.add(cid);
  const c = doc.collections[cid];
  if (!c) return out;
  for (const id of c.objects) if (doc.objects[id]) out.add(id);
  for (const ch of c.children) collectionObjectIds(doc, ch, out, seen);
  return out;
}

function childrenOf(doc: DocumentData, id: string): ObjectData[] {
  return Object.values(doc.objects).filter((o) => o.parent === id);
}

/** Orientation of a face: Z along the normal, X along its first edge. */
function faceFrame(P: ArrayLike<number>, idx: number[]): { center: Vector3; basis: Matrix4; area: number } {
  const center = new Vector3();
  for (const v of idx) center.add(new Vector3(P[v * 3], P[v * 3 + 1], P[v * 3 + 2]));
  center.multiplyScalar(1 / idx.length);
  const n = new Vector3();
  for (let i = 0; i < idx.length; i++) {
    const a = idx[i],
      b = idx[(i + 1) % idx.length];
    n.x += (P[a * 3 + 1] - P[b * 3 + 1]) * (P[a * 3 + 2] + P[b * 3 + 2]);
    n.y += (P[a * 3 + 2] - P[b * 3 + 2]) * (P[a * 3] + P[b * 3]);
    n.z += (P[a * 3] - P[b * 3]) * (P[a * 3 + 1] + P[b * 3 + 1]);
  }
  const area = n.length() / 2;
  n.normalize();
  if (n.lengthSq() < 0.5) n.set(0, 0, 1);
  const x = new Vector3(P[idx[1] * 3] - P[idx[0] * 3], P[idx[1] * 3 + 1] - P[idx[0] * 3 + 1], P[idx[1] * 3 + 2] - P[idx[0] * 3 + 2]);
  x.addScaledVector(n, -x.dot(n));
  if (x.lengthSq() < 1e-12) x.set(1, 0, 0);
  x.normalize();
  const y = new Vector3().crossVectors(n, x);
  return { center, basis: new Matrix4().makeBasis(x, y, n), area };
}

/** Area-weighted vertex normals. */
function vertexNormals(P: ArrayLike<number>, offsets: ArrayLike<number>, indices: ArrayLike<number>): Float32Array {
  const out = new Float32Array(P.length);
  for (let f = 0; f + 1 < offsets.length; f++) {
    const idx: number[] = [];
    for (let c = offsets[f]; c < offsets[f + 1]; c++) idx.push(indices[c]);
    if (idx.length < 3) continue;
    const { basis, area } = faceFrame(P, idx);
    const n = new Vector3().setFromMatrixColumn(basis, 2).multiplyScalar(area);
    for (const v of idx) {
      out[v * 3] += n.x;
      out[v * 3 + 1] += n.y;
      out[v * 3 + 2] += n.z;
    }
  }
  return out;
}

/** Instances generated by one object (empty when it does not instance anything). */
export function objectDuplis(doc: DocumentData, graph: Depsgraph, ob: ObjectData, depth = 0): Dupli[] {
  const ev = graph.get(ob.id);
  if (!ev || depth > MAX_DEPTH) return [];
  const out: Dupli[] = [];
  if (ob.instance_type === 'COLLECTION' && ob.instance_collection && doc.collections[ob.instance_collection]) {
    const off = doc.collections[ob.instance_collection].instance_offset ?? [0, 0, 0];
    const base = ev.world.clone().multiply(new Matrix4().makeTranslation(-off[0], -off[1], -off[2]));
    for (const id of collectionObjectIds(doc, ob.instance_collection)) {
      if (id === ob.id) continue;
      const src = doc.objects[id];
      const sev = graph.get(id);
      if (!src || !sev) continue;
      if (src.instance_type === 'COLLECTION') {
        // nested collection instance: what it shows, placed by this instance
        for (const d of objectDuplis(doc, graph, src, depth + 1)) out.push({ source: d.source, matrix: base.clone().multiply(d.matrix) });
        continue;
      }
      if (sev.mesh?.indices.length) out.push({ source: id, matrix: base.clone().multiply(sev.world) });
    }
    return out;
  }
  if ((ob.instance_type === 'VERTS' || ob.instance_type === 'FACES') && ev.mesh) {
    const kids = childrenOf(doc, ob.id).filter((c) => graph.get(c.id)?.mesh?.indices.length);
    if (!kids.length) return out;
    const W = ev.world;
    const Winv = W.clone().invert();
    const rel = kids.map((k) => ({ id: k.id, m: Winv.clone().multiply(graph.get(k.id)!.world) }));
    const P = ev.mesh.positions;
    if (ob.instance_type === 'VERTS') {
      const normals = ob.use_instance_vertices_rotation ? vertexNormals(P, ev.mesh.offsets, ev.mesh.indices) : null;
      const up = new Vector3(0, 0, 1);
      for (let v = 0; v < P.length / 3; v++) {
        const t = new Matrix4().makeTranslation(P[v * 3], P[v * 3 + 1], P[v * 3 + 2]);
        if (normals) {
          const n = new Vector3(normals[v * 3], normals[v * 3 + 1], normals[v * 3 + 2]);
          if (n.lengthSq() > 1e-12) t.multiply(new Matrix4().makeRotationFromQuaternion(new Quaternion().setFromUnitVectors(up, n.normalize())));
        }
        for (const r of rel) out.push({ source: r.id, matrix: W.clone().multiply(t).multiply(r.m) });
      }
    } else {
      const { offsets, indices } = ev.mesh;
      const useScale = !!ob.use_instance_faces_scale;
      const factor = ob.instance_faces_scale ?? 1;
      for (let f = 0; f + 1 < offsets.length; f++) {
        const idx: number[] = [];
        for (let c = offsets[f]; c < offsets[f + 1]; c++) idx.push(indices[c]);
        if (idx.length < 3) continue;
        const fr = faceFrame(P, idx);
        const s = useScale ? Math.sqrt(fr.area) * factor : 1;
        const m = new Matrix4().makeTranslation(fr.center.x, fr.center.y, fr.center.z).multiply(fr.basis).multiply(new Matrix4().makeScale(s, s, s));
        for (const r of rel) out.push({ source: r.id, matrix: W.clone().multiply(m).multiply(r.m) });
      }
    }
  }
  return out;
}

/** Cheap fingerprint of everything the instances of `ob` depend on. */
function dupliKey(doc: DocumentData, graph: Depsgraph, ev: EvalObject): string {
  const ob = ev.ob;
  if (ob.instance_type === 'NONE' || !ob.instance_type) return '';
  const parts: string[] = [ob.instance_type, ev.world.elements.join(',')];
  const add = (id: string) => {
    const e = graph.get(id);
    if (e) parts.push(id, String(e.geomVersion), e.world.elements.join(','), JSON.stringify(materialSlots(doc, e.ob)));
  };
  if (ob.instance_type === 'COLLECTION') {
    if (!ob.instance_collection) return '';
    const c = doc.collections[ob.instance_collection];
    parts.push(JSON.stringify(c?.instance_offset ?? null));
    const visit = (cid: string, depth: number) => {
      for (const id of collectionObjectIds(doc, cid)) {
        add(id);
        const o = doc.objects[id];
        if (o?.instance_type === 'COLLECTION' && o.instance_collection && depth < MAX_DEPTH) visit(o.instance_collection, depth + 1);
      }
    };
    visit(ob.instance_collection, 0);
  } else {
    parts.push(String(ev.geomVersion), String(ob.use_instance_faces_scale), String(ob.instance_faces_scale), String(ob.use_instance_vertices_rotation));
    for (const k of childrenOf(doc, ob.id)) add(k.id);
  }
  return parts.join('|');
}

/** Instances grouped by source object. */
function groupDuplis(duplis: Dupli[]): Map<string, Matrix4[]> {
  const out = new Map<string, Matrix4[]>();
  for (const d of duplis) {
    const list = out.get(d.source);
    if (list) list.push(d.matrix);
    else out.set(d.source, [d.matrix]);
  }
  return out;
}

