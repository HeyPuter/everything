// viewport

type WithDuplis = SyncedObject & { dupliKey?: string };

sceneSyncHooks.push((doc, ev, so) => {
  const s = so as WithDuplis;
  const graph = app?.graph;
  if (!graph) return;
  const key = dupliKey(doc, graph, ev);
  if (key === (s.dupliKey ?? '')) return;
  s.dupliKey = key;
  if (s.duplis) {
    s.root.remove(s.duplis);
    for (const c of s.duplis.children) (c as InstancedMesh).dispose?.();
    s.duplis = undefined;
  }
  if (!key) return;
  const duplis = objectDuplis(doc, graph, ev.ob);
  if (!duplis.length) return;
  const g = new Group();
  g.matrixAutoUpdate = false;
  const inv = ev.world.clone().invert();
  for (const [src, mats] of groupDuplis(duplis)) {
    const mesh = graph.get(src)?.mesh;
    if (!mesh) continue;
    const im = new InstancedMesh(meshGeometry(mesh).geometry, undefined as unknown as Material, mats.length);
    mats.forEach((m, i) => im.setMatrixAt(i, inv.clone().multiply(m)));
    im.instanceMatrix.needsUpdate = true;
    im.computeBoundingSphere();
    im.matrixAutoUpdate = false;
    im.userData.id = ev.id;
    im.userData.instanced = true;
    im.userData.source = src;
    im.castShadow = true;
    im.receiveShadow = true;
    g.add(im);
  }
  s.duplis = g;
  s.root.add(g);
});

