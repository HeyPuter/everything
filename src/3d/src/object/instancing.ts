// make instances real

registerOperators([
  {
    idname: 'object.duplicates_make_real',
    label: 'Make Instances Real',
    description: 'Turn the instances shown by the selected objects into real objects',
    props: [{ id: 'use_base_parent', label: 'Parent', type: 'bool', default: false }],
    poll: (ctx) => ctx.doc.mode === 'OBJECT' && app.selectedObjects().some((o) => !!o.instance_type && o.instance_type !== 'NONE'),
    exec: (ctx, p) => {
      const doc = ctx.doc;
      const made: ObjectData[] = [];
      for (const inst of app.selectedObjects()) {
        if (!inst.instance_type || inst.instance_type === 'NONE') continue;
        const duplis = objectDuplis(doc, app.graph, inst);
        const iw = app.graph.get(inst.id)!.world;
        for (const d of duplis) {
          const src = doc.objects[d.source];
          if (!src) continue;
          const c = duplicateObject(doc, src, true);
          for (const cc of Object.values(doc.collections)) cc.objects = cc.objects.filter((x) => x !== c.id);
          doc.collections[activeCollection(doc)].objects.push(c.id);
          c.parent = null;
          c.matrix_parent_inverse = [...IDENTITY];
          if (p.use_base_parent) {
            c.parent = inst.id;
            applyMatrixToObject(c, iw.clone().invert().multiply(d.matrix));
          } else applyMatrixToObject(c, d.matrix);
          c.select = true;
          made.push(c);
        }
        if (inst.instance_type === 'COLLECTION') {
          inst.instance_type = 'NONE';
          inst.instance_collection = null;
        } else inst.instance_type = 'NONE';
        inst.select = false;
      }
      if (!made.length) return 'CANCELLED';
      doc.scene.active_object = made[made.length - 1].id;
    },
  },
]);

