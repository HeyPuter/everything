/**
 * The profile registry: every profile the app can convert with, by id.
 *
 *   built-in RGB   the RGB working spaces of color-management.js ('srgb',
 *                  'p3', ...), generated as ICC matrix/curve profiles
 *   built-in Gray  'gray22', 'gray18', 'dotgain20' (generated ICC gray profiles)
 *   press models   the CMYK printing conditions ('coatedWeb', ...): the
 *                  analytic press model is the engine model, and an
 *                  equivalent ICC output profile (lut16 tables sampled
 *                  from the model) is generated on demand for embedding
 *                  and saving
 *   'lab'          CIE L*a*b* (D50)
 *   'icc:<hash>'   profiles from .icc/.icm files the user loaded
 *                  (source 'user') or found in documents ('embedded')
 *
 * Entry: { id, name, kind ('RGB' | 'CMYK' | 'Gray' | 'Lab' | ...), source,
 *          deviceClass, model() (cached engine model), bytes() (ICC data) }
 */
import { RGB_SPACES, CMYK_PROFILES, externalProfiles, cmykProfile, simulatePlates, platesFor, blackPoint as pressBlack, dotGain } from '../prepress/color-management.js';
import { parseProfile, profileSummary, ICCError } from './parse.js';
import { writeProfile, sampleClut, identityCurve } from './write.js';
import { modelFromProfile, createTransform } from './transform.js';
import { D50, srgbToPcs, pcsToSrgb, rgbToPcsMatrix, adaptation, xyToXYZ, labToXyz, xyzToLab, clamp01, deltaE } from './math.js';
import { Emitter } from '../../lib/emitter.js';

export const registryEvents = new Emitter();

const FIXED_DATE = new Date(Date.UTC(2026, 0, 1));
const COPYRIGHT = 'Generated by Vector Studio. No rights reserved.';

const entries = new Map();

// ---- generated RGB and gray profiles ----

const SRGB_CURVE = { kind: 'para', type: 3, params: [2.4, 1 / 1.055, 0.055 / 1.055, 1 / 12.92, 0.04045] };
const gammaCurve = (g) => ({ kind: 'para', type: 0, params: [g] });
const RGB_CURVES = { srgb: SRGB_CURVE, p3: SRGB_CURVE, monitor: SRGB_CURVE, rec709: gammaCurve(2.4), rec2020: gammaCurve(2.4), wide: gammaCurve(2.2), mac18: gammaCurve(1.8) };

/** ICC bytes of a matrix/curve RGB profile (v2 by default; v4 on request). */
export function rgbProfileBytes({ name, primaries, white, curve, version = 2 }) {
  const M = rgbToPcsMatrix(primaries, white);
  const col = (i) => ({ kind: 'XYZ', values: [[M[i], M[3 + i], M[6 + i]]] });
  // v2 curves only have gamma and table forms; parametric curves are sampled.
  const c = version >= 4 || curve.type === 0 ? (version >= 4 ? curve : { kind: 'gamma', gamma: curve.params[0] }) : { kind: 'table', table: sampleCurve(curve, 1024) };
  const trc = { kind: 'curve', curve: c };
  const W = xyToXYZ(white);
  const tags = [
    ['desc', { kind: 'text', text: name }],
    ['cprt', { kind: 'text', text: COPYRIGHT }],
    ['wtpt', { kind: 'XYZ', values: [version >= 4 ? D50.slice() : W] }],
    ['rXYZ', col(0)],
    ['gXYZ', col(1)],
    ['bXYZ', col(2)],
    ['rTRC', trc],
    ['gTRC', trc],
    ['bTRC', trc],
    ['chad', { kind: 'sf32', values: adaptation(W, D50) }],
  ];
  return writeProfile({ version, deviceClass: 'mntr', colorSpace: 'RGB ', pcs: 'XYZ ', tags, date: FIXED_DATE });
}

function sampleCurve(c, n) {
  const [g, a, b, cc, d] = c.params;
  const t = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const x = i / (n - 1);
    t[i] = c.type === 3 ? (x >= d ? (a * x + b) ** g : cc * x) : x ** g;
  }
  return t;
}

const GRAY_SPACES = {
  gray22: { label: 'Gray Gamma 2.2', curve: (v) => v ** 2.2 },
  gray18: { label: 'Gray Gamma 1.8', curve: (v) => v ** 1.8 },
  dotgain20: { label: 'Gray Dot Gain 20%', curve: (v) => 1 - dotGain(1 - v, 0.2) },
};

function grayProfileBytes(id) {
  const g = GRAY_SPACES[id];
  const table = new Float64Array(256);
  for (let i = 0; i < 256; i++) table[i] = clamp01(g.curve(i / 255));
  const tags = [
    ['desc', { kind: 'text', text: g.label }],
    ['cprt', { kind: 'text', text: COPYRIGHT }],
    ['wtpt', { kind: 'XYZ', values: [D50.slice()] }],
    ['kTRC', { kind: 'curve', curve: { kind: 'table', table } }],
  ];
  return writeProfile({ version: 2, deviceClass: id === 'dotgain20' ? 'prtr' : 'mntr', colorSpace: 'GRAY', pcs: 'XYZ ', tags, date: FIXED_DATE });
}

// ---- press models as profiles ----

const chroma = (rgb, k) => {
  const l = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2];
  return rgb.map((v) => clamp01(l + (v - l) * k));
};

/**
 * Engine model of a press model. Colorimetric intents use the press as it
 * prints (paper = PCS white, its real black); perceptual and saturation
 * map the press black to PCS black, compress (perceptual) or push
 * (saturation) chroma, as perceptual tables of print profiles do.
 */
export function pressModel(id) {
  const p = cmykProfile(id);
  const black = pressBlack(id);
  const rescale = (rgb) => rgb.map((v, i) => clamp01((v - black[i]) / Math.max(1e-6, 1 - black[i])));
  const blackY = srgbToPcs(black)[1];
  return {
    key: `press:${id}`,
    name: p.label,
    colorSpace: 'CMYK',
    channels: 4,
    deviceClass: 'prtr',
    version: 2,
    press: id,
    // Separating solves for plates per color: bake tables on a coarser grid.
    costly: true,
    mediaWhite: srgbToPcs(hex3(p.paper)),
    toPcs: (intent) => (intent === 'perceptual' || intent === 'saturation' ? (v) => srgbToPcs(rescale(simulatePlates(id, v))) : (v) => srgbToPcs(simulatePlates(id, v))),
    fromPcs: (intent) => {
      if (intent === 'perceptual') return (x) => platesFor(chroma(pcsToSrgb(x), 0.92), id, { blackMap: true });
      if (intent === 'saturation') return (x) => platesFor(chroma(pcsToSrgb(x), 1.1), id, { blackMap: true });
      return (x) => platesFor(pcsToSrgb(x), id, { blackMap: false });
    },
    blackPoint: (intent) => (intent === 'perceptual' || intent === 'saturation' ? [0, 0, 0] : [D50[0] * blackY, blackY, D50[2] * blackY]),
  };
}

function hex3(hex) {
  const n = parseInt(String(hex || '#000000').slice(1), 16) || 0;
  return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
}

/** ICC output profile equivalent to a press model (v2, CMYK, Lab PCS, lut16 tables). */
export function pressProfileBytes(id, { a2bGrid = 9, b2aGrid = 17 } = {}) {
  const model = pressModel(id);
  const L = 65535 / 65280;
  const AB = 65535 / 256;
  const encLab = (xyz) => {
    const lab = xyzToLab(xyz);
    return [lab[0] / 100 / L, (lab[1] + 128) / AB, (lab[2] + 128) / AB];
  };
  const decLab = (v) => labToXyz([v[0] * L * 100, v[1] * AB - 128, v[2] * AB - 128]);
  const lut = (inputs, outputs, clut) => ({ kind: 'lut', bits: 16, inputs, outputs, matrix: null, inCurves: new Array(inputs).fill(identityCurve), clut, outCurves: new Array(outputs).fill(identityCurve) });
  const a2b = (intent) => {
    const fn = model.toPcs(intent);
    return lut(4, 3, sampleClut(4, 3, a2bGrid, (v) => encLab(fn(v))));
  };
  const b2a = (intent) => {
    const fn = model.fromPcs(intent);
    return lut(3, 4, sampleClut(3, 4, b2aGrid, (v) => fn(decLab(v))));
  };
  const toRel = model.toPcs('relative');
  const fromRel = model.fromPcs('relative');
  const gamut = lut(3, 1, sampleClut(3, 1, b2aGrid, (v) => {
    const xyz = decLab(v);
    const back = toRel(fromRel(xyz));
    return [deltaE(xyzToLab(xyz), xyzToLab(back)) > 3 ? 1 : 0];
  }));
  const perceptual = a2b('perceptual');
  const tags = [
    ['desc', { kind: 'text', text: model.name }],
    ['cprt', { kind: 'text', text: COPYRIGHT }],
    ['wtpt', { kind: 'XYZ', values: [model.mediaWhite] }],
    ['A2B0', perceptual],
    ['A2B1', a2b('relative')],
    ['A2B2', perceptual],
    ['B2A0', b2a('perceptual')],
    ['B2A1', b2a('relative')],
    ['B2A2', b2a('saturation')],
    ['gamt', gamut],
  ];
  return writeProfile({ version: 2, deviceClass: 'prtr', colorSpace: 'CMYK', pcs: 'Lab ', intent: 0, tags, date: FIXED_DATE });
}

// ---- Lab ----

export const LAB_MODEL = Object.freeze({
  key: 'lab',
  name: 'CIE L*a*b* (D50)',
  colorSpace: 'Lab ',
  channels: 3,
  deviceClass: 'spac',
  version: 4,
  mediaWhite: D50.slice(),
  toPcs: () => (v) => labToXyz([v[0] * 100, v[1] * 255 - 128, v[2] * 255 - 128]),
  fromPcs: () => (x) => {
    const lab = xyzToLab(x);
    return [clamp01(lab[0] / 100), clamp01((lab[1] + 128) / 255), clamp01((lab[2] + 128) / 255)];
  },
  blackPoint: () => [0, 0, 0],
});

/**
 * A model for a calibrated (CIE-based) space: white point XYZ, per-channel
 * gamma and an optional 3x3 matrix (columns: XYZ of each channel), as PDF
 * CalRGB and CalGray spaces describe them.
 */
export function calibratedModel({ white = [0.9505, 1, 1.089], gamma = [1, 1, 1], matrix = null, channels = 3 } = {}) {
  const adapt = adaptation(white, D50);
  const M = matrix ? [matrix[0], matrix[3], matrix[6], matrix[1], matrix[4], matrix[7], matrix[2], matrix[5], matrix[8]] : [1, 0, 0, 0, 1, 0, 0, 0, 1];
  const toXyz = channels === 1
    ? (v) => { const y = clamp01(v[0]) ** (gamma[0] || 1); return mulv(adapt, [white[0] * y, white[1] * y, white[2] * y]); }
    : (v) => mulv(adapt, mulv(M, [0, 1, 2].map((i) => clamp01(v[i]) ** (gamma[i] || 1))));
  return {
    key: `cal:${white.join(',')}:${gamma.join(',')}:${(matrix || []).join(',')}`,
    name: channels === 1 ? 'Calibrated Gray' : 'Calibrated RGB',
    colorSpace: channels === 1 ? 'GRAY' : 'RGB ',
    channels,
    deviceClass: 'spac',
    version: 2,
    mediaWhite: D50.slice(),
    toPcs: () => toXyz,
    fromPcs: () => null,
  };
}

const mulv = (m, v) => [m[0] * v[0] + m[1] * v[1] + m[2] * v[2], m[3] * v[0] + m[4] * v[1] + m[5] * v[2], m[6] * v[0] + m[7] * v[1] + m[8] * v[2]];

// ---- registry ----

function lazy(fn) {
  let done = false;
  let value;
  return () => {
    if (!done) {
      value = fn();
      done = true;
    }
    return value;
  };
}

function addBuiltins() {
  for (const [id, s] of Object.entries(RGB_SPACES)) {
    const bytes = lazy(() => rgbProfileBytes({ name: s.label, primaries: s.primaries, white: s.white, curve: RGB_CURVES[id] || SRGB_CURVE }));
    entries.set(id, { id, name: s.label, kind: 'RGB', source: 'builtin', deviceClass: 'mntr', bytes, model: lazy(() => ({ ...modelFromProfile(parseProfile(bytes()), `builtin:${id}`), name: s.label })) });
  }
  for (const [id, g] of Object.entries(GRAY_SPACES)) {
    const bytes = lazy(() => grayProfileBytes(id));
    entries.set(id, { id, name: g.label, kind: 'Gray', source: 'builtin', deviceClass: id === 'dotgain20' ? 'prtr' : 'mntr', bytes, model: lazy(() => modelFromProfile(parseProfile(bytes()), `builtin:${id}`)) });
  }
  for (const [id, p] of Object.entries(CMYK_PROFILES)) {
    entries.set(id, { id, name: p.label, kind: 'CMYK', source: 'builtin', deviceClass: 'prtr', press: true, bytes: lazy(() => pressProfileBytes(id)), model: lazy(() => pressModel(id)) });
  }
  entries.set('lab', { id: 'lab', name: LAB_MODEL.name, kind: 'Lab', source: 'builtin', deviceClass: 'spac', bytes: () => null, model: () => LAB_MODEL });
}
addBuiltins();

/** Stable id of profile data. */
export function profileHash(bytes) {
  let a = 0x811c9dc5;
  let b = 0x01000193;
  for (let i = 0; i < bytes.length; i++) {
    a = Math.imul(a ^ bytes[i], 16777619);
    b = Math.imul(b + bytes[i], 2246822519) ^ (b >>> 13);
  }
  return `${(a >>> 0).toString(16).padStart(8, '0')}${(b >>> 0).toString(16).padStart(8, '0')}`;
}

/**
 * Register ICC data (from a file, a document or a PDF). Returns the entry;
 * the same data always gets the same id. Throws ICCError for data that is
 * not a usable profile.
 */
export function registerIccProfile(input, { source = 'user', name = null } = {}) {
  const bytes = input instanceof Uint8Array ? input : new Uint8Array(input);
  const id = `icc:${profileHash(bytes)}`;
  const existing = entries.get(id);
  if (existing) {
    // A profile the user loaded stays theirs even when a document carries it too.
    if (source === 'user' && existing.source !== 'user') {
      existing.source = 'user';
      registryEvents.emit('change', { id });
    }
    return existing;
  }
  const parsed = parseProfile(bytes);
  const model = modelFromProfile(parsed, id);
  // Check it can convert in the direction its class needs.
  if (!model.toPcs('relative') && !model.toPcs('perceptual')) throw new ICCError('This profile cannot convert colors to the connection space.');
  const sum = profileSummary(parsed);
  const entry = { id, name: name || sum.name, kind: sum.kind, source, deviceClass: parsed.deviceClass, version: sum.version, classLabel: sum.classLabel, bytes: () => parsed.bytes, model: () => model, parsed };
  entries.set(id, entry);
  externalProfiles.set(id, { kind: entry.kind, label: entry.name });
  registryEvents.emit('change', { id });
  return entry;
}

export function unregisterProfile(id) {
  const e = entries.get(id);
  if (!e || e.source === 'builtin') return false;
  entries.delete(id);
  externalProfiles.delete(id);
  registryEvents.emit('change', { id });
  return true;
}

export function profileEntry(id) {
  return entries.get(id) || null;
}

export function isProfileId(id) {
  return entries.has(id);
}

/** Entries of a kind ('RGB' | 'CMYK' | 'Gray'), built-ins first. `outputOnly` keeps profiles that can be converted to. */
export function listProfiles(kind = null, { outputOnly = false } = {}) {
  const out = [];
  for (const e of entries.values()) {
    if (kind && e.kind !== kind) continue;
    if (outputOnly) {
      try {
        if (!e.model().fromPcs('relative') && !e.model().fromPcs('perceptual')) continue;
      } catch {
        continue;
      }
    }
    out.push(e);
  }
  const rank = { builtin: 0, user: 1, embedded: 2 };
  return out.sort((a, b) => rank[a.source] - rank[b.source] || (a.source === 'builtin' ? 0 : a.name.localeCompare(b.name)));
}

/** Engine model of a profile id, or null. */
export function profileModel(id) {
  const e = entries.get(id);
  if (!e) return null;
  try {
    return e.model();
  } catch {
    return null;
  }
}

/** ICC data of a profile id (generated for built-ins), or null. */
export function profileBytes(id) {
  const e = entries.get(id);
  return e ? e.bytes() : null;
}

export function profileName(id) {
  return entries.get(id)?.name || null;
}

const transformCache = new Map();
/** Cached transform between two profile ids (or models). Returns null when either side is unknown or unusable. */
export function transformBetween(src, dst, opts = {}) {
  const s = typeof src === 'string' ? profileModel(src) : src;
  const d = typeof dst === 'string' ? profileModel(dst) : dst;
  if (!s || !d) return null;
  const key = `${s.key}>${d.key}|${opts.intent || 'relative'}|${opts.bpc ? 1 : 0}`;
  let t = transformCache.get(key);
  if (t === undefined) {
    try {
      t = createTransform(s, d, opts);
    } catch {
      t = null;
    }
    if (transformCache.size > 64) transformCache.delete(transformCache.keys().next().value);
    transformCache.set(key, t);
  }
  return t;
}
