const attrs = (a: Record<string, string | number>) =>
  Object.entries(a)
    .map(([k, v]) => `${k}="${v}"`)
    .join(' ');
const cache = new Map<string, string>();
/** Inline SVG markup for an icon name (kebab-case Lucide name or original glyph). */
export function svg(name: string, size = 18) {
  const key = `${name}:${size}`;
  let out = cache.get(key);
  if (out) return out;
  let children = custom[name] ?? (lucide[name]?.[2] as Node[] | undefined);
  if (!children) {
    // An unknown name is a bug; show a neutral glyph and say so during development.
    if (import.meta.env?.DEV) console.warn(`Unknown icon "${name}"`);
    children = custom['note'];
  }
  out = `<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${children
    .map(([tag, a]) => `<${tag} ${attrs(a)}/>`)
    .join('')}</svg>`;
  cache.set(key, out);
  return out;
}
