const cache = new Map<BuiltinProfileId, Profile>();
// Profiles are built on first use; the CMYK ones take a moment (see cmyk-model).
export function builtinProfile(id: BuiltinProfileId): Profile {
  let p = cache.get(id);
  if (!p) {
    p = factories[id].make();
    cache.set(id, p);
  }
  return p;
}
export const BUILTIN_PROFILES = (Object.keys(factories) as BuiltinProfileId[]).map((id) => ({
  id,
  name: factories[id].name,
  colorSpace: factories[id].colorSpace,
}));
