// Built-in profiles generated in code from published primaries and transfer
// functions; no third-party profile files are shipped. The CMYK profiles come
// from Photo Studio's own analytic printing model (cmyk-model.ts) and are
// approximations, not certified press characterizations.
import { srgbProfile } from './profile';
import type { Curve } from './profile';
import { bradfordMatrix, D50, rgbToXYZMatrix, xyToXYZ, type Vec3 } from './color-math';
import type { Profile } from './icc-lut';
import { buildCmykProfile, GENERIC_COATED, GENERIC_UNCOATED } from './cmyk-model';

const D65xy: [number, number] = [0.3127, 0.329];
const D50xy: [number, number] = [0.3457, 0.3585];
const SRGB: Curve = { kind: 'srgb' };
const gamma = (g: number): Curve => ({ kind: 'parametric', type: 0, parameters: [g] });

function matrixProfile(
  key: string,
  name: string,
  matrix: number[],
  white: [number, number],
  curve: Curve,
): Profile {
  const w = xyToXYZ(white[0], white[1]);
  const isD50 = Math.abs(white[0] - D50xy[0]) < 1e-4 && Math.abs(white[1] - D50xy[1]) < 1e-4;
  return {
    name,
    copyright: 'Generated by Photo Studio from published primaries; no copyright.',
    version: 4.3,
    deviceClass: 'mntr',
    colorSpace: 'RGB',
    channels: 3,
    pcs: 'XYZ',
    renderingIntent: 0,
    mediaWhite: [...D50],
    chad: isD50 ? undefined : bradfordMatrix(w, D50),
    matrix,
    trc: [curve, curve, curve],
    a2b: [undefined, undefined, undefined],
    b2a: [undefined, undefined, undefined],
    key: `builtin:${key}`,
  };
}

function grayProfile(key: string, name: string, curve: Curve): Profile {
  return {
    name,
    copyright: 'Generated by Photo Studio; no copyright.',
    version: 4.3,
    deviceClass: 'mntr',
    colorSpace: 'GRAY',
    channels: 1,
    pcs: 'XYZ',
    renderingIntent: 0,
    mediaWhite: [...D50],
    trc: [curve],
    a2b: [undefined, undefined, undefined],
    b2a: [undefined, undefined, undefined],
    key: `builtin:${key}`,
  };
}

// 20% dot gain at the 50% tone with a parabolic tone value increase; 100% ink
// is taken as Y = 0 so the profile behaves as a pure tone curve.
function dotGainCurve(gain: number): Curve {
  const values = Array.from({ length: 1024 }, (_, i) => {
    const k = 1 - i / 1023;
    return 1 - (k + 4 * gain * k * (1 - k));
  });
  return { kind: 'table', values };
}

// ROMM RGB (ISO 22028-2): gamma 1.8 with a linear toe below 1/512.
const ROMM: Curve = { kind: 'parametric', type: 3, parameters: [1.8, 1, 0, 1 / 16, 16 / 512] };
// ITU-R BT.2020 transfer (alpha/beta at full precision), decoded as ICC type 3.
const BT_A = 1.09929682680944,
  BT_B = 0.018053968510807;
const REC2020: Curve = {
  kind: 'parametric',
  type: 3,
  parameters: [1 / 0.45, 1 / BT_A, (BT_A - 1) / BT_A, 1 / 4.5, 4.5 * BT_B],
};

